/**
 * Builds the exact version-2 schema (as generated by Room for the released v2 entities), fills it
 * with legacy data, then opens it with the current AppDatabase. Room runs MIGRATION_2_3 and
 * validates the migrated schema against the v3 entities, so a wrong column type/nullability or a
 * missing index fails this test.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [36], application = Application::class)
class MigrationTest {
    private val context: Context = ApplicationProvider.getApplicationContext()
    private val dbName = "migration-test.db"

    @Before fun setUp() { context.deleteDatabase(dbName) }
    @After fun tearDown() { context.deleteDatabase(dbName) }

    private fun createV2(seed: (SupportSQLiteDatabase) -> Unit) {
        val config = SupportSQLiteOpenHelper.Configuration.builder(context).name(dbName)
            .callback(object : SupportSQLiteOpenHelper.Callback(2) {
                override fun onCreate(db: SupportSQLiteDatabase) { V2_SCHEMA.forEach(db::execSQL) }
                override fun onUpgrade(db: SupportSQLiteDatabase, oldVersion: Int, newVersion: Int) = Unit
            }).build()
        val helper = FrameworkSQLiteOpenHelperFactory().create(config)
        seed(helper.writableDatabase)
        helper.close()
    }

    @Test
    fun migrate2To3PreservesAllData() {
        createV2 { db ->
            db.execSQL("INSERT INTO users VALUES ('u1','1234567890',NULL,'sara','Sara','abc123hash',NULL,'Hi',0,1000,0,'#4F46E5',900)")
            db.execSQL("INSERT INTO users VALUES ('u2','2234567890',NULL,'omar','Omar',NULL,NULL,'',0,1000,0,'#0D9488',900)")
            db.execSQL("INSERT INTO conversations VALUES ('c1',0,'Omar',NULL,'u1,u2','second',2000,'u2',0,1,500)")
            db.execSQL("INSERT INTO conversations VALUES ('c2',0,'Gemini',NULL,'u1,user_gemini_ai','ai',1500,'user_gemini_ai',3,0,500)")
            db.execSQL("INSERT INTO messages VALUES ('m1','c1','u1','u2','first','TEXT','READ',1000,NULL,0,NULL,0,NULL,NULL,NULL,NULL,NULL,NULL,NULL)")
            db.execSQL("INSERT INTO messages VALUES ('m2','c1','u2','u1','second','TEXT','SENT',2000,NULL,0,'m1',0,NULL,NULL,NULL,NULL,NULL,NULL,NULL)")
            db.execSQL("INSERT INTO messages VALUES ('m3','c1','u1',NULL,'Lunch?','POLL','SENT',1500,NULL,0,NULL,0,NULL,NULL,NULL,NULL,'Lunch?','Yes|No','2,1')")
            db.execSQL("INSERT INTO contacts VALUES ('k1','u1','u2','Omy',1,700)")
            db.execSQL("INSERT INTO calls VALUES ('call1','u1','Sara','u2','Omar',1,'ENDED',1800,42)")
            db.execSQL("INSERT INTO statuses VALUES ('s1','u2','Omar',NULL,'hello',NULL,'TEXT','DEFAULT','#3730A3',100,99999999999,0)")
        }

        val db = Room.databaseBuilder(context, AppDatabase::class.java, dbName)
            .addMigrations(*Migrations.ALL)
            .allowMainThreadQueries()
            .build()
        runBlocking {
            val legacy = db.userDao().get("u1")!!
            assertEquals("sara", legacy.username)
            assertEquals("abc123hash", legacy.passwordHash)
            assertEquals(0L, legacy.profileSyncedAt)

            val c1 = db.conversationDao().get("c1")!!
            assertTrue(c1.isLocalOnly)
            assertTrue(c1.isPinned)
            assertEquals(2000L, c1.pinnedAt)
            assertEquals(2000L, c1.lastReadAt) // fully read chats keep their read state
            assertEquals("m2", c1.lastMessageId)
            assertFalse(c1.isArchived)
            assertTrue(c1.onlyAdminsCanEditInfo)
            assertEquals(listOf("u1", "u2"), c1.getParticipantsList())

            val c2 = db.conversationDao().get("c2")!!
            assertTrue(c2.isAiConversation)
            assertEquals(0L, c2.lastReadAt) // had unread messages
            assertEquals(3, c2.unreadCount)

            val m1 = db.messageDao().get("m1")!!
            assertEquals("first", m1.content)
            assertEquals(MessageStatus.READ, m1.status)
            assertEquals(1000L, m1.updatedAt)
            assertEquals(TransferState.NONE, m1.transferState)
            assertFalse(m1.deletedForEveryone)
            assertEquals("m1", db.messageDao().get("m2")!!.replyToMessageId)

            val poll = db.messageDao().get("m3")!!
            assertEquals(MessageType.POLL, poll.type)
            assertEquals(listOf(2, 1), poll.pollCounts())

            assertEquals(listOf("u2"), db.contactDao().blockedIds("u1"))
            assertEquals("Omy", db.contactDao().get("u1", "u2")!!.customNickname)
            assertEquals(CallState.ENDED, db.callDao().get("call1")!!.state)
            val status = db.statusDao().get("s1")!!
            assertEquals("DONE", status.uploadState)
            assertNull(status.localMediaPath)
        }
        db.close()
    }

    @Test
    fun legacyIdentityRemapKeepsHistoryVisible() {
        createV2 { db ->
            db.execSQL("INSERT INTO users VALUES ('old','1234567890',NULL,'sara','Sara','h',NULL,'',0,1,0,'#4F46E5',1)")
            db.execSQL("INSERT INTO conversations VALUES ('c1',0,'Omar',NULL,'old,u2','x',2000,'old',0,0,500)")
            db.execSQL("INSERT INTO messages VALUES ('m1','c1','old','u2','x','TEXT','SENT',2000,NULL,0,NULL,0,NULL,NULL,NULL,NULL,NULL,NULL,NULL)")
        }
        val db = Room.databaseBuilder(context, AppDatabase::class.java, dbName).addMigrations(*Migrations.ALL).allowMainThreadQueries().build()
        runBlocking {
            val dao = db.legacyMigrationDao()
            dao.remapParticipants("old", "newUid")
            dao.remapSenders("old", "newUid")
            dao.remapLastSender("old", "newUid")
            val c = db.conversationDao().get("c1")!!
            assertEquals(listOf("newUid", "u2"), c.getParticipantsList())
            assertEquals("newUid", c.lastMessageSenderId)
            assertEquals("newUid", db.messageDao().get("m1")!!.senderId)
        }
        db.close()
    }

    companion object {
        /** Schema of database version 2 exactly as Room generated it (exportSchema was off then). */
        val V2_SCHEMA = listOf(
            "CREATE TABLE IF NOT EXISTS `users` (`userId` TEXT NOT NULL, `uniqueId10` TEXT NOT NULL, `googleId` TEXT, `username` TEXT NOT NULL, " +
                "`displayName` TEXT NOT NULL, `passwordHash` TEXT, `avatarUrl` TEXT, `statusMessage` TEXT NOT NULL, `isOnline` INTEGER NOT NULL, " +
                "`lastSeen` INTEGER NOT NULL, `isAiAssistant` INTEGER NOT NULL, `avatarColorHex` TEXT NOT NULL, `createdAt` INTEGER NOT NULL, PRIMARY KEY(`userId`))",
            "CREATE TABLE IF NOT EXISTS `conversations` (`conversationId` TEXT NOT NULL, `isGroup` INTEGER NOT NULL, `title` TEXT NOT NULL, `avatarUrl` TEXT, " +
                "`participantIds` TEXT NOT NULL, `lastMessageText` TEXT, `lastMessageTimestamp` INTEGER NOT NULL, `lastMessageSenderId` TEXT, " +
                "`unreadCount` INTEGER NOT NULL, `isPinned` INTEGER NOT NULL, `createdAt` INTEGER NOT NULL, PRIMARY KEY(`conversationId`))",
            "CREATE TABLE IF NOT EXISTS `messages` (`messageId` TEXT NOT NULL, `conversationId` TEXT NOT NULL, `senderId` TEXT NOT NULL, `recipientId` TEXT, " +
                "`content` TEXT NOT NULL, `type` TEXT NOT NULL, `status` TEXT NOT NULL, `createdAt` INTEGER NOT NULL, `mediaUrl` TEXT, " +
                "`mediaDurationSeconds` INTEGER NOT NULL, `replyToMessageId` TEXT, `isAiGenerated` INTEGER NOT NULL, `fileName` TEXT, `fileSize` TEXT, " +
                "`locationLat` REAL, `locationLng` REAL, `pollQuestion` TEXT, `pollOptions` TEXT, `pollVotes` TEXT, PRIMARY KEY(`messageId`))",
            "CREATE INDEX IF NOT EXISTS `index_messages_conversationId` ON `messages` (`conversationId`)",
            "CREATE INDEX IF NOT EXISTS `index_messages_createdAt` ON `messages` (`createdAt`)",
            "CREATE INDEX IF NOT EXISTS `index_messages_senderId` ON `messages` (`senderId`)",
            "CREATE TABLE IF NOT EXISTS `contacts` (`contactId` TEXT NOT NULL, `ownerUserId` TEXT NOT NULL, `targetUserId` TEXT NOT NULL, " +
                "`customNickname` TEXT, `isBlocked` INTEGER NOT NULL, `addedAt` INTEGER NOT NULL, PRIMARY KEY(`contactId`))",
            "CREATE UNIQUE INDEX IF NOT EXISTS `index_contacts_ownerUserId_targetUserId` ON `contacts` (`ownerUserId`, `targetUserId`)",
            "CREATE TABLE IF NOT EXISTS `calls` (`callId` TEXT NOT NULL, `callerId` TEXT NOT NULL, `callerName` TEXT NOT NULL, `receiverId` TEXT NOT NULL, " +
                "`receiverName` TEXT NOT NULL, `isVideo` INTEGER NOT NULL, `state` TEXT NOT NULL, `timestamp` INTEGER NOT NULL, " +
                "`durationSeconds` INTEGER NOT NULL, PRIMARY KEY(`callId`))",
            "CREATE TABLE IF NOT EXISTS `statuses` (`statusId` TEXT NOT NULL, `userId` TEXT NOT NULL, `authorName` TEXT NOT NULL, `authorPhotoUrl` TEXT, " +
                "`text` TEXT, `mediaUrl` TEXT, `mediaType` TEXT NOT NULL, `fontFamily` TEXT NOT NULL, `backgroundColorHex` TEXT NOT NULL, " +
                "`createdAt` INTEGER NOT NULL, `expiresAt` INTEGER NOT NULL, `isViewed` INTEGER NOT NULL, PRIMARY KEY(`statusId`))",
        )
    }
}
