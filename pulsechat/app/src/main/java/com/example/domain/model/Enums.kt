package com.example.domain.model

/**
 * Core enums shared by the UI, the Room schema (stored by name as TEXT) and the sync layer.
 * Never rename or remove existing constants: persisted rows reference them by name.
 */
enum class MessageType {
    TEXT,
    IMAGE,
    VIDEO,
    AUDIO,       // Voice note
    DOCUMENT,
    LOCATION,
    POLL,
    CALL_EVENT,  // Audio/video call summary
    AI_RESPONSE, // Generated by Gemini (only inside the AI assistant conversation)
    CONTACT,
    SYSTEM;      // Group events such as "X added Y"

    val isMedia: Boolean get() = this == IMAGE || this == VIDEO || this == AUDIO || this == DOCUMENT
    val isVisualMedia: Boolean get() = this == IMAGE || this == VIDEO
}

/**
 * Delivery state of a message. Outgoing messages advance only on real events:
 * PENDING (queued locally, offline) -> SENDING (write/upload in flight) -> SENT (server ack)
 * -> DELIVERED (recipient device stored it) -> READ (recipient opened it). FAILED is terminal
 * until the user retries.
 */
enum class MessageStatus { PENDING, SENDING, SENT, DELIVERED, READ, FAILED }

/** Upload/download state of a media attachment. */
enum class TransferState { NONE, UPLOADING, UPLOAD_FAILED, UPLOADED, DOWNLOADING, DOWNLOAD_FAILED, DOWNLOADED }

/**
 * Call states. The first seven constants are legacy values that may exist in stored call history.
 */
enum class CallState {
    IDLE, CALLING, RINGING, ACCEPTED, REJECTED, ENDED, FAILED,
    INITIATING, CONNECTING, CONNECTED, RECONNECTING, BUSY, MISSED, CANCELLED;

    val isTerminal: Boolean
        get() = this == REJECTED || this == ENDED || this == FAILED || this == BUSY || this == MISSED || this == CANCELLED

    val isActive: Boolean
        get() = this == ACCEPTED || this == CONNECTING || this == CONNECTED || this == RECONNECTING
}

enum class ChatFilter { ALL, UNREAD, FAVORITES, GROUPS }

/** Who may see a piece of profile/presence information. */
enum class Visibility { EVERYONE, CONTACTS, NOBODY;
    companion object {
        fun parse(value: String?): Visibility = entries.firstOrNull { it.name.equals(value, ignoreCase = true) } ?: EVERYONE
    }
}
