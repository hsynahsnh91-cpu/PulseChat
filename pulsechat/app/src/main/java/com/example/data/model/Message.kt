package com.example.data.model

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

enum class MessageType {
    TEXT,
    IMAGE,
    VIDEO,
    AUDIO,       // Voice note
    DOCUMENT,
    LOCATION,
    POLL,
    CALL_EVENT,  // Audio/video call summary
    AI_RESPONSE  // Generated by Gemini AI
}

enum class MessageStatus {
    SENDING,
    SENT,
    DELIVERED,
    READ,
    FAILED
}

@Entity(
    tableName = "messages",
    indices = [
        Index("conversationId"),
        Index("createdAt"),
        Index("senderId")
    ]
)
data class Message(
    @PrimaryKey
    val messageId: String = "",
    val conversationId: String = "",
    val senderId: String = "",
    val recipientId: String? = null,
    val content: String = "",
    val type: MessageType = MessageType.TEXT,
    val status: MessageStatus = MessageStatus.SENT,
    val createdAt: Long = System.currentTimeMillis(),
    val mediaUrl: String? = null,
    val mediaDurationSeconds: Int = 0,
    val replyToMessageId: String? = null,
    val isAiGenerated: Boolean = false,
    val fileName: String? = null,
    val fileSize: String? = null,
    val locationLat: Double? = null,
    val locationLng: Double? = null,
    val pollQuestion: String? = null,
    val pollOptions: String? = null, // Pipe-separated options: "نعم|لا|ربما"
    val pollVotes: String? = null    // Comma-separated counts: "0,0,0"
)
